-- Run before starting the updated application on an existing database.
BEGIN;
LOCK TABLE brand_requests IN ACCESS EXCLUSIVE MODE;
ALTER TABLE brand_requests ADD COLUMN IF NOT EXISTS user_id bigint;
UPDATE brand_requests r SET user_id = u.id FROM users u
WHERE r.user_id IS NULL AND r.requested_by = u.username;
-- Fails and rolls back if an existing requester cannot be resolved; never deletes requests.
ALTER TABLE brand_requests ALTER COLUMN user_id SET NOT NULL;
DO $$ BEGIN
IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_brand_requests_user' AND conrelid = 'brand_requests'::regclass) THEN
ALTER TABLE brand_requests ADD CONSTRAINT fk_brand_requests_user FOREIGN KEY (user_id) REFERENCES users(id);
END IF;
END $$;
CREATE INDEX IF NOT EXISTS idx_brand_requests_user ON brand_requests(user_id);
CREATE TABLE IF NOT EXISTS brand_follows (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id),
    brand_id varchar(50) NOT NULL REFERENCES brands(id),
    created_at timestamp with time zone NOT NULL DEFAULT current_timestamp,
    UNIQUE(user_id, brand_id)
);
CREATE INDEX IF NOT EXISTS idx_brand_follows_brand ON brand_follows(brand_id);
COMMIT;
